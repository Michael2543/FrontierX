inline bool EqualAsciiInsensitive(const char *left, const char *right)
{
    for (;; ++left, ++right)
    {
        unsigned char a = *left, b = *right;
        if (a >= 'A' && a <= 'Z') a += 'a' - 'A';
        if (b >= 'A' && b <= 'Z') b += 'a' - 'A';
        if (a != b) return false;
        if (!a) return true;
    }
}
inline wchar_t *DuplicateWide(const wchar_t *text)
{
    if (!text) return nullptr;
    const auto bytes = (std::wcslen(text)+1)*sizeof(wchar_t);
    auto *copy = static_cast<wchar_t *>(std::malloc(bytes));
    if (copy) std::memcpy(copy, text, bytes);
    return copy;
}
inline wchar_t *DecimalToWide(S32 value, wchar_t *out, int radix)
{
    if (!out || radix != 10) std::abort();
    wchar_t number[16];
    const int size = std::swprintf(number, 16, L"%d", value);
    if (size < 0) std::abort();
    std::wcscpy(out, number);
    return out;
}
// Original English hotkey labels are byte strings. Fail on a label that needs
// an unimplemented code-page conversion, matching the bounded native strings.
inline int ConvertHotkeyToWide(const char *text, int length, wchar_t *out, int capacity)
{
    if (!text || !out || length < 0 || length > capacity) std::abort();
    for (int i=0; i<length; ++i)
    {
        const auto ch = static_cast<unsigned char>(text[i]);
        if (ch >= 0x80) std::abort();
        out[i] = ch;
    }
    return length;
}
inline constexpr U32 WM_COMMAND = 0x0111; // Windows editor menu; not generated by SDL.
inline constexpr U32 WM_MOUSEFIRST = 0x0200;
inline constexpr U32 WM_MOUSELAST = 0x020a;
inline U32 LOWORD(std::uintptr_t value) { return value & 0xffff; }
inline U32 HIWORD(std::uintptr_t value) { return (value >> 16) & 0xffff; }
inline FrontierX::LegacyLParam MAKELPARAM(S32 x, S32 y)
{
    return static_cast<FrontierX::LegacyLParam>((static_cast<U32>(x) & 0xffff) |
        ((static_cast<U32>(y) & 0xffff) << 16));
}
struct MessageFields
{
    FrontierX::LegacyWParam wParam = 0;
    FrontierX::LegacyLParam lParam = 0;
};
inline bool DecodeMessage(U32 message, void *parameter, MessageFields &fields)
{
    if (message != WM_CLOSE && message != WM_COMMAND && message != WM_KEYDOWN &&
        message != WM_CHAR && (message < WM_MOUSEFIRST || message > WM_MOUSELAST)) return true;
    const auto *record = static_cast<const FrontierX::LegacyWindowMessage *>(parameter);
    if (!record || record->message != message) return false;
    fields.wParam = record->wparam;
    fields.lParam = record->lparam;
    return true;
}
